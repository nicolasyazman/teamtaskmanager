CREATE TABLE USERS (
    ID SERIAL PRIMARY KEY,
    USERNAME VARCHAR(255),
    EMAIL VARCHAR(255),
    PASSWORD VARCHAR(255),
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

CREATE TABLE PROJECTS (
    ID SERIAL PRIMARY KEY,
    NAME VARCHAR(255),
    DESCRIPTION TEXT,
    OWNER_ID INTEGER,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT ownerid_fk FOREIGN KEY (OWNER_ID) REFERENCES USERS(ID)
);

CREATE TABLE TASKS (
    ID SERIAL PRIMARY KEY,
    TITLE VARCHAR(255),
    DESCRIPTION TEXT,
    STATUS VARCHAR(50),
    PRIORITY INTEGER,
    DUE_DATE TIMESTAMP,
    PROJECT_ID INTEGER,
    CREATED_BY INTEGER,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT projectid_fk FOREIGN KEY (PROJECT_ID) REFERENCES PROJECTS(ID),
    CONSTRAINT createdby_fk FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID)
);

CREATE TABLE TASK_ASSIGNMENT (
    ID SERIAL PRIMARY KEY,
    TASK_ID INTEGER,
    USER_ID INTEGER,
    CONSTRAINT taskid_fk FOREIGN KEY (TASK_ID) REFERENCES TASKS(ID),
    CONSTRAINT userid_fk FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

CREATE TABLE PROJECT_CONTRIBUTOR (
    ID SERIAL PRIMARY KEY,
    PROJECT_ID INTEGER,
    USER_ID INTEGER,
    CONSTRAINT pc_project_fk FOREIGN KEY (PROJECT_ID) REFERENCES PROJECTS(ID),
    CONSTRAINT pc_user_fk FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

